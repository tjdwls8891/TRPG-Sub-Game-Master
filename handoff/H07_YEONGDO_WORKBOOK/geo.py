def bearing_ko(a, b):
    (x1, y1, _), (x2, y2, _) = C[a], C[b]
    ang = math.degrees(math.atan2(y2 - y1, x2 - x1)) % 360
    return DIRS[int(((ang + 22.5) % 360) // 45)]


def tobler_factor(grade):
    """Tobler 보행 함수의 평지 대비 시간 배수(오르막·급내리막은 느리고, 완만한 내리막은 약간 빠르다)."""
    return math.exp(3.5 * abs(grade + 0.05)) / math.exp(3.5 * 0.05)


def edge_metrics(a, b, terrain):
    (x1, y1, h1), (x2, y2, h2) = C[a], C[b]
    wind, tf = TERRAIN[terrain]
    euc = math.hypot(x2 - x1, y2 - y1)
    dist = max(20, int(round(euc * wind / 10.0)) * 10)
    if terrain in ("sewer", "interior", "ladder", "climb"):
        slope = 1.0
    else:
        slope = tobler_factor((h2 - h1) / dist)
    factor = round(tf * slope, 2)
    return dist, factor, h2 - h1


def slope_word(dh, dist):
    g = dh / dist if dist else 0
    if g > 0.12:
        return "가파른 오르막"
    if g > 0.04:
        return "오르막"
    if g < -0.12:
        return "가파른 내리막"
    if g < -0.04:
        return "내리막"
    return "평탄"
