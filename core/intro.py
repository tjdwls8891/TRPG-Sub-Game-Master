#
# [기획 규정]
#   버튼식 케이스 트리 구조로 플레이어 인지 수준 및 설명 따라,
#   고인지 수준엔 동일 메시지 바리에이션 랜덤선택 재생,
#   첫 플레이면 스킵 선택지 안 주고 풀소개.
#   경험자면 케이스 맞춰 질문해가며 진행.
#
# [바리에이션]
#   초심자에게는 고정 문안을 쓴다. 처음 배우는 사람에게 표현이 매번
#   달라지면 오히려 혼란스럽다. 경험자 이상에게만 랜덤 선택한다.
import random

# 인지 수준
LEVEL_NEW = "new"          # 첫 플레이 — 스킵 없이 풀소개
LEVEL_KNOWN = "known"      # 경험자 — 묻고 답하며, 원하면 풀소개도 가능
LEVEL_VETERAN = "veteran"  # 숙련자 — 최소 안내, 바리에이션

# 숙련자 판정 기준
VETERAN_SESSIONS = 3
VETERAN_TURNS = 60


def judge_level(user_stats: dict, scenario_id: str = "") -> str:
    """인지 수준을 판정한다.

    통계가 없으면 첫 플레이로 본다. 세션 수와 턴 수를 함께 보는 이유는,
    세션만 여러 번 열고 실제로 플레이하지 않은 경우를 걸러내기 위해서다.
    """
    st = user_stats or {}
    sessions = int(st.get("sessions", 0) or 0)
    turns = int(st.get("turns", 0) or 0)
    played = st.get("played_scenarios") or []

    if sessions <= 0 and turns <= 0:
        return LEVEL_NEW
    if sessions >= VETERAN_SESSIONS or turns >= VETERAN_TURNS:
        return LEVEL_VETERAN
    if scenario_id and scenario_id in played:
        return LEVEL_VETERAN
    return LEVEL_KNOWN


