def get_body(key: str, level: str) -> str:
    """항목 본문. 초심자에게는 고정 문안, 그 외에는 바리에이션."""
    topic = TOPICS.get(key)
    if not topic:
        return ""
    if level == LEVEL_NEW:
        return topic["body"]
    alts = topic.get("alts") or []
    return random.choice(alts) if alts else topic["body"]


def get_label(key: str) -> str:
    return (TOPICS.get(key) or {}).get("label", key)


def greeting(level: str) -> str:
    if level == LEVEL_VETERAN:
        return random.choice(VETERAN_GREETINGS)
    if level == LEVEL_KNOWN:
        return random.choice(KNOWN_GREETINGS)
    return ("처음이시군요. 이 놀이가 무엇인지부터 차근히 안내해 드리겠습니다.\n"
            "여섯 가지를 순서대로 보여드립니다.")


def media_for(key: str, scenario_data: dict = None) -> str | None:
    """항목에 곁들일 이미지 파일명. 시나리오가 지정한 것이 있으면 쓴다.

    기획 규정의 '미디어 활용한 설명'. 자산이 없으면 None을 반환해
    텍스트만 나간다.
    """
    imgs = (scenario_data or {}).get("intro_images") or {}
    return imgs.get(key)
