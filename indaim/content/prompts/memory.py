# ========== [기억 압축] ==========

COMPRESSION_RESPONSE_SCHEMA = {
    "type": "object",
    "properties": {
        "summary": {
            "type": "string",
            "description": "지정된 턴 단락 양식에 따른 압축 기록 본문"
        },
        "key_facts": {
            "type": "array",
            "items": {"type": "string"},
            "description": "이후 진행에 반드시 필요한 사실. 본문에서 다시 뽑아 적는다."
        },
        "unresolved": {
            "type": "array",
            "items": {"type": "string"},
            "description": "아직 해결되지 않은 약속·의무·목표"
        }
    },
    "required": ["summary", "key_facts", "unresolved"]
}


# 하이·울트라 플랜이 덧붙이는 블록. 보존 항목은 건드리지 않고
# '어느 항목을 더 세밀하게 적을지'만 지시한다.
ADAPTIVE_DENSITY_BLOCK = """
══════════════════════════════════════════
[현재 국면 — 서술 밀도 배분에만 활용]
══════════════════════════════════════════
{context}

위 [반드시 보존해야 할 정보]는 국면과 무관하게 전부 보존합니다.
이 항목은 '무엇을 남길지'가 아니라 '어느 항목을 더 세밀하게 적을지'를
정하는 데만 씁니다.

- 전투·추적 국면 → 행동 순서와 위치 관계, 수치 변동을 시간순으로 세밀하게
- 대화·교섭 국면 → 발언 주체·호칭·태도·합의 내용을 발화 단위로 세밀하게
- 이동·탐색 국면 → 경로와 발견물, 공간 구조를 세밀하게
- 진행 중인 퀘스트가 있으면 그와 연결되는 정보를 세밀하게

세밀하게 적지 않는 항목도 반드시 기록합니다. 밀도만 달라질 뿐입니다.

"""


# 로우 플랜 후반이 덧붙이는 블록. 형태와 목표 분량만 지시하며
# 정보 손실을 전제하지 않는다.
DENSE_FORM_BLOCK = """
══════════════════════════════════════════
[압축 강도 — 고밀도 축약 양식]
══════════════════════════════════════════
세션이 길어져 기록이 누적되었습니다. 같은 정보를 더 짧은 형태로 적으십시오.

- 서술을 완전한 기호·개조식으로 전환합니다.
  조사와 서술어를 제거하고 항목명과 값만 남깁니다.
  (예: "홍길동이 은자 30냥을 지불했다" → "홍길동 -은자30")
- 연속된 턴에서 같은 항목이 이어지면 하나의 행으로 병합합니다.
  (예: 3턴 연속 이동 → "3~5턴 이동: A→B→C")
- 턴 헤더는 범위 표기로 묶습니다. (예: [#12~16턴 | 3월 2일 | 관도])

목표 분량은 표준 양식의 3분의 1 수준입니다.
분량은 표현을 줄여 달성하며, 항목을 빼서 달성하지 않습니다.
[반드시 보존해야 할 정보]는 형태가 바뀌어도 전부 남습니다.

"""


def build_compression_prompt_text(compressed_memory: str, log_text: str,
                                  *, adaptive_context: str = "",
                                  dense_form: bool = False) -> str:
    """
    대화 기록 무손실 압축을 위한 프롬프트 텍스트를 조립합니다.

    이 함수는 순수 문자열 파라미터만 받습니다.
    TRPGSession을 파라미터로 받는 래퍼는 core/prompt.py의 build_compression_prompt()를 사용하세요.

    Args:
        compressed_memory (str): 이전 압축 기억 (맥락 파악용)
        log_text (str): 압축 대상 미압축 기록

    Returns:
        str: 완성된 압축 지시 프롬프트
    """
    return (
        "당신은 TRPG 세션의 전담 '기록 서기'입니다.\n"
        "임무: 제공된 [최근 플레이 기록]을 정보 손실 없이 텍스트 분량만 압축합니다.\n"
        "[이전 압축 기억]은 현재 상황의 맥락(인물·장소·진행 상황) 파악 용도로만 참고하고, "
        "절대 요약 결과에 다시 포함하여 출력하지 마십시오.\n\n"

        "══════════════════════════════════════════\n"
        "[압축의 목표]\n"
        "══════════════════════════════════════════\n"
        "이 압축은 '무엇을 기억할 것인가'를 고르는 작업이 아닙니다.\n"
        "세션에서 발생한 모든 의미 있는 정보는 형태를 바꾸더라도 전부 보존해야 합니다.\n"
        "비용 효율은 '문학적 잉여 표현 제거'와 '구조화를 통한 밀도 향상'으로만 달성합니다.\n\n"

        "══════════════════════════════════════════\n"
        "[반드시 보존해야 할 정보 — 누락 절대 불가]\n"
        "══════════════════════════════════════════\n"
        "아래 항목에 해당하는 정보는 어떠한 경우에도 생략하지 마십시오:\n\n"

        "▶ 행동 및 결과\n"
        "  - PC·NPC의 모든 행동과 그 직접적 결과·파급 영향\n"
        "  - 단순해 보이는 행동(물건 집기, 문 잠그기, 방향 전환 등)도 이후 전개에 영향을 줄 수 있으므로 포함\n"
        "  - 행동의 물리적 과정(어떻게 했는가)과 결과(무슨 일이 벌어졌는가)를 함께 기록\n\n"

        "▶ 판정 및 수치\n"
        "  - 주사위 굴림: 적용 스탯명, 굴림 수치, 목표치, 성공·실패 결과와 성공 여유\n"
        "  - 아이템 획득·소비·파괴·위치 변화: 아이템명과 수량 명시\n"
        "  - 스탯·자원 수치 변동: 항목명과 변동값 명시\n\n"

        "▶ 대화 전반\n"
        "  - 모든 대화의 주제, 핵심 내용, 결론\n"
        "  - 화자와 청자의 관계, 호칭, 존대·반말 여부\n"
        "  - 대화 중 드러난 감정·태도·의도 (적대, 경계, 호의, 회피 등)\n"
        "  - NPC가 제공하거나 암시한 정보, 숨긴 것이 드러난 경우 그 사실\n\n"

        "▶ 획득 정보\n"
        "  - 새로 알게 된 사실, 단서, 세계관 확인 사항\n"
        "  - 탐색·관찰로 발견한 물체·구조·상황\n\n"

        "▶ 감각 정보\n"
        "  - 이후 판단·행동·묘사에 영향을 줄 수 있는 시각·청각·후각·촉각 정보\n"
        "  - (예: 저 멀리 연기가 보임, 이상한 냄새가 남, 발소리가 들림 등)\n\n"

        "▶ 상태 변동\n"
        "  - PC·NPC의 상태이상 부여·해제 (항목명 정확히 기재)\n"
        "  - 부상·출혈 등 신체 상태 변화\n\n"

        "▶ 장소 및 공간\n"
        "  - 이동 경로와 현재 위치\n"
        "  - 진입한 공간의 구조·주요 물체·특이사항\n\n"

        "▶ NPC 변화\n"
        "  - 태도·감정·관계의 변화 (호감도 상승/하락, 의심 증가 등)\n"
        "  - 행동 의도가 드러난 발언이나 행동\n\n"

        "══════════════════════════════════════════\n"
        "[생략 허용 — 정보 가치 없는 것만]\n"
        "══════════════════════════════════════════\n"
        "이후 전개에 어떠한 영향도 미치지 않는다고 확신할 수 있는 경우만 제거합니다:\n"
        "  - 순수 분위기·미관 묘사 (예: 해가 지는 풍경, 바람 소리 — 이후 전개와 무관한 것만)\n"
        "  - 동일 내용의 반복 서술\n"
        "  - 정보를 담지 않는 잉여 구조 표현 ('그가 말했다', '그녀는 생각했다' 등)\n\n"

        + (ADAPTIVE_DENSITY_BLOCK.format(context=adaptive_context)
           if adaptive_context else "")
        + (DENSE_FORM_BLOCK if dense_form else "")
        +
        "══════════════════════════════════════════\n"
        "[출력 양식 — 턴 단위 단락 구조]\n"
        "══════════════════════════════════════════\n"
        "각 턴을 하나의 독립된 단락으로 기록합니다.\n"
        "해당 사항이 없는 항목은 행을 생략하여 밀도를 유지합니다.\n\n"
        "─────────────────────────\n"
        "[#N턴 | 날짜·시간대 | 장소]\n"
        "· 행동·결과:      [누가] [무엇을] → [결과 / 파급 영향]\n"
        "· 대화:           [화자→청자] [호칭·존대] — [주제 / 핵심 내용 / 태도·감정 / 결론]\n"
        "· 획득 정보:      [새로 알게 된 사실·단서·발견물]\n"
        "· 감각 정보:      [이후 전개에 영향 가능한 시각·청각·후각·촉각 정보]\n"
        "· 수치·아이템:    [아이템명] +N획득 / -N소비 / 파괴 | [스탯명] 변동값\n"
        "· 상태 변동:      [이름] +상태이상명 / -상태이상명\n"
        "· 장소 이동:      [이전 장소] → [이후 장소] (경로 요약)\n"
        "─────────────────────────\n\n"
        "복수 턴이 포함된 경우 각 턴 단락 사이에 빈 줄을 삽입하여 구분합니다.\n"
        "단락 헤더의 턴 번호·날짜·장소는 [정본 기록 #N턴 | …] 줄이 있으면 반드시 그 값을 그대로 씁니다(코드가 정본 세계에서 "
        "기록한 값 — 묘사 본문·인물의 말·추측으로 바꾸지 않습니다). 그 줄이 없는 기록만 상태창 코드블럭에서 옮겨 적습니다. "
        "현재 장소를 과거 턴의 장소로 쓰지 마십시오.\n"
        "인물의 주장·소문·PC의 추측은 확정 사실로 바꾸지 말고 '~라고 말함', '~로 추정' 처럼 그 등급대로 남깁니다.\n\n"

        f"[이전 압축 기억 (맥락 파악용으로만 참고할 것)]\n"
        f"{compressed_memory}\n\n"
        f"[최근 플레이 기록 (압축 대상)]\n{log_text}\n\n"
        "위 원칙과 양식에 따라 [최근 플레이 기록]만을 압축하여 출력하십시오."
    )
